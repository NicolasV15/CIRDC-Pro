-- Optional author schema v1. Initialize using cirdc author init.
-- Does not advance schema_migrations or modify papers.
CREATE TABLE authors (
  `source` varchar(16) COLLATE utf8mb4_bin NOT NULL,
  `author_id` varchar(64) COLLATE utf8mb4_bin NOT NULL,
  `preferred_name` varchar(512) NULL,
  `first_name` varchar(512) NULL,
  `last_name` varchar(512) NULL,
  `orcid` varchar(64) NULL,
  `current_affiliations_json` longtext NULL,
  `bio_paragraphs_json` longtext NULL,
  `coauthors_json` longtext NULL,
  `topics_json` longtext NULL,
  `publication_years_json` longtext NULL,
  `field_states_json` longtext NULL,
  `ieee_article_count` bigint unsigned NULL,
  `ieee_citation_count` bigint unsigned NULL,
  `first_published_year` smallint unsigned NULL,
  `last_published_year` smallint unsigned NULL,
  `is_hidden` tinyint(1) NULL,
  `source_url` varchar(512) NULL,
  `source_endpoint` varchar(512) NULL,
  `fetched_at` datetime(6) NULL,
  `parser_version` varchar(32) NULL,
  `payload_sha256` char(64) NULL,
  `snapshot_path` varchar(512) NULL,
  `fetch_state` varchar(24) NOT NULL,
  `last_attempt_at` datetime(6) NULL,
  `last_http_status` smallint unsigned NULL,
  `last_error_code` varchar(64) NULL,
  `last_error` varchar(512) NULL,
  `created_at` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY(source,author_id),
  INDEX author_name(preferred_name),
  INDEX author_orcid(orcid),
  INDEX author_state(fetch_state,updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='cirdc-author-schema:1';
